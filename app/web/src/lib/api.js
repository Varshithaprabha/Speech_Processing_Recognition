// App backend (python server.py, port 8000): history, custom phrases, clips.
// Same origin in production (served by server.py) and in dev (Vite proxy).

async function j(path, opts) {
  const r = await fetch(path, {
    headers: { 'Content-Type': 'application/json' },
    ...opts,
  })
  if (!r.ok) throw new Error(`${path}: ${r.status}`)
  return r.json()
}

export const api = {
  history: () => j('/api/history'),
  conversation: (id) => j(`/api/history/${id}`),
  save: (data) => j('/api/history', { method: 'POST', body: JSON.stringify(data) }),
  remove: (id) => j(`/api/history/${id}`, { method: 'DELETE' }),
  phrases: () => j('/api/phrases'),
  savePhrases: (list) => j('/api/phrases', { method: 'PUT', body: JSON.stringify(list) }),
}

export const clipUrl = (file) => `/clips/${encodeURIComponent(file)}`

const indexCache = { p: null }
export function clipIndex() {
  indexCache.p ??= fetch('/clips/index.json')
    .then((r) => (r.ok ? r.json() : {}))
    .catch(() => ({}))
  return indexCache.p
}

export async function quickReplies(speechUrl) {
  try {
    const r = await fetch(speechUrl.replace(/\/$/, '') + '/quick_replies')
    if (r.ok) return await r.json()
  } catch {
    /* fall through */
  }
  return FALLBACK_QUICK
}

