export function download(name, text, type = 'text/plain') {
  const url = URL.createObjectURL(new Blob([text], { type: `${type};charset=utf-8` }))
  const a = Object.assign(document.createElement('a'), { href: url, download: name })
  document.body.appendChild(a)
  a.click()
  a.remove()
  setTimeout(() => URL.revokeObjectURL(url), 1000)
}

const who = (m) => (m.from === 'signer' ? 'Deaf user (signed)' : m.from === 'speaker' ? 'Hearing person' : 'System')

export function toText(conv) {
  const lines = [
    conv.title,
    new Date(conv.created_at || Date.now()).toLocaleString(),
    '',
    'SUMMARY',
    conv.summary || '(none)',
    ...(conv.key_points?.length ? ['', 'KEY POINTS', ...conv.key_points.map((p) => `- ${p}`)] : []),
    '',
    'TRANSCRIPT',
    ...(conv.transcript || []).map((m) => {
      const t = m.timestamp ? new Date(m.timestamp).toLocaleTimeString() : ''
      const orig = m.original && m.original !== m.text ? `  [${m.original}]` : ''
      const tag = m.emotion && m.emotion !== 'neutral' ? ` (${m.emotion})` : ''
      return `[${t}] ${who(m)}${tag}: ${m.text}${orig}`
    }),
    ...(conv.signs?.length ? ['', `SIGNS USED: ${conv.signs.join(', ')}`] : []),
    '',
    'Generated by SignBridge.',
  ]
  return lines.join('\n')
}

const esc = (t) => String(t ?? '').replace(/[&<>"]/g, (c) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' })[c])

/** Printable page (and "Save as PDF") in a new window, e.g. to hand to a doctor. */
export function printConversation(conv) {
  const w = window.open('', '_blank')
  if (!w) return
  const rows = (conv.transcript || [])
    .map(
      (m) => `<tr><td>${esc(m.timestamp ? new Date(m.timestamp).toLocaleTimeString() : '')}</td>
      <td><b>${esc(who(m))}</b>${m.emotion && m.emotion !== 'neutral' ? ` <i>(${esc(m.emotion)})</i>` : ''}</td>
      <td>${esc(m.text)}${m.original && m.original !== m.text ? `<br><small>${esc(m.original)}</small>` : ''}</td></tr>`,
    )
    .join('')
  w.document.write(`<!doctype html><meta charset="utf-8"><title>${esc(conv.title)}</title>
<style>body{font:14px/1.5 system-ui,sans-serif;max-width:800px;margin:2rem auto;color:#111}
h1{font-size:1.4rem;margin:0}table{border-collapse:collapse;width:100%}td{border-top:1px solid #ccc;padding:6px;vertical-align:top}
td:first-child{white-space:nowrap;color:#555}.box{background:#f2f7f6;border:1px solid #9cc;padding:12px;border-radius:8px}</style>
<h1>${esc(conv.title)}</h1><p>${esc(new Date(conv.created_at || Date.now()).toLocaleString())}</p>
<div class="box"><b>Summary</b><p>${esc(conv.summary || '(none)')}</p>${
    conv.key_points?.length ? `<ul>${conv.key_points.map((p) => `<li>${esc(p)}</li>`).join('')}</ul>` : ''
  }</div><h2>Transcript</h2><table>${rows}</table><p><small>Generated by SignBridge.</small></p>`)
  w.document.close()
  w.focus()
  setTimeout(() => w.print(), 300)
}
